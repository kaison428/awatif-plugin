// Bundles the viewer's source modules (skills/awatif-ui/src/viewer) into the
// single ES module the design system ships: skills/awatif-ui/assets/awatif-viewer.js.
// three stays external, so pages resolve it with an import map (see scaffold.py).
import { dirname } from "node:path";
import { viewerAsset, viewerSrc } from "./paths.mjs";

const BANNER = `/* Awatif viewer (awatif-ui): the required three.js viewport. GENERATED by \`npm run build\` from
 * skills/awatif-ui/src/viewer/ -- edit the source there, never this file. API and usage: src/viewer/index.js
 * and SKILL.md. ES module; resolve "three" and "three/addons/" with a bundler or an import map. */`;

export function viewerConfig() {
  return {
    configFile: false,
    logLevel: "warn",
    build: {
      outDir: dirname(viewerAsset),
      emptyOutDir: false,
      minify: false,
      target: "es2022",
      lib: { entry: viewerSrc, formats: ["es"], fileName: () => "awatif-viewer.js" },
      rolldownOptions: {
        external: ["three", /^three\/addons\//],
        output: { banner: BANNER },
      },
    },
  };
}
